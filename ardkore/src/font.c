static unsigned char glyph_bits[FONT_GLYPHS][7];
static int glyphs_ready;

static void build_glyphs(void)
{
    for (int g = 0; g < FONT_GLYPHS; g++)
        for (int y = 0; y < 7; y++) {
            unsigned char row = 0;
            for (int x = 0; x < 5; x++)
                if (glyph_art[g][y][x] == '#') row |= (unsigned char)(1 << (4 - x));
            glyph_bits[g][y] = row;
        }
    glyphs_ready = 1;
}

const unsigned char *font_glyph(int c)
{
    if (!glyphs_ready) build_glyphs();
    int g;
    if (c >= 'a' && c <= 'z') c -= 32;
    if (c >= 32 && c <= 95) g = c - 32;
    else if (c == FONT_PLAY) g = 64;
    else if (c == FONT_STOP) g = 65;
    else if (c == '|') g = 66;
    else if (c == FONT_DOT) g = 67;
    else g = '?' - 32;
    return glyph_bits[g];
}
